import pandas as pd
import os
import shutil

# 1. Load the metadata (this file tells us which image has which disease)
data = pd.read_csv('skin_data/HAM10000_metadata.csv')

# 2. Define the path where images currently are and where we want them to go
raw_image_path = 'skin_data/'
base_dir = 'skin_data/organized_images/'

# 3. Create folders for each disease type
disease_types = data['dx'].unique()
for disease in disease_types:
    os.makedirs(os.path.join(base_dir, disease), exist_ok=True)

# 4. Move images into their respective folders
# This looks at the 'image_id' and 'dx' (disease) columns in the CSV
for index, row in data.iterrows():
    img_name = row['image_id'] + '.jpg'
    disease = row['dx']

    # Check both part_1 and part_2 folders for the image
    for part in ['ham10000_images_part_1/', 'ham10000_images_part_2/']:
        source = os.path.join(raw_image_path, part, img_name)
        if os.path.exists(source):
            destination = os.path.join(base_dir, disease, img_name)
            shutil.copy(source, destination)

print("Images have been organized into disease folders!")

import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# 1. Define the size and batching
IMG_HEIGHT = 224
IMG_WIDTH = 224
BATCH_SIZE = 32

# 2. Setup the "Generator" (This prepares the images)
datagen = ImageDataGenerator(
    rescale=1./255,             # Changes pixel values from 0-255 to 0-1
    validation_split=0.2,       # Uses 20% of images for testing later
    rotation_range=20,          # Randomly rotate images
    horizontal_flip=True        # Randomly flip images
)

# 3. Create Training Data
train_data = datagen.flow_from_directory(
    'skin_data/organized_images/',
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='training'
)

# 4. Create Validation Data (to check if the AI is learning correctly)
val_data = datagen.flow_from_directory(
    'skin_data/organized_images/',
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='validation'
)

print("Data is ready for the AI!")

from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras import layers, models

# 1. Load the pre-trained MobileNetV2 "brain"
base_model = MobileNetV2(input_shape=(224, 224, 3), include_top=False, weights='imagenet')

# 2. Freeze the base (don't change the parts that already know colors/shapes)
base_model.trainable = False

# 3. Add new layers for skin diseases
model = models.Sequential([
    base_model,
    layers.GlobalAveragePooling2D(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.3), # Helps prevent the AI from "memorizing" images
    layers.Dense(7, activation='softmax') # 7 categories of disease
])

# 4. Compile the model
model.compile(optimizer='adam',
              loss='categorical_crossentropy',
              metrics=['accuracy'])

model.summary()

# We will train for 5 "epochs" (passes through the data)
# This will take about 5-10 minutes.
history = model.fit(
    train_data,
    validation_data=val_data,
    epochs=5
)

import numpy as np
from google.colab import files
from tensorflow.keras.preprocessing import image
import matplotlib.pyplot as plt

# 1. Dictionary to map the AI's answer back to human names
# These are the 7 classes from the HAM10000 dataset
disease_map = {
    0: 'Actinic keratoses (akiec)',
    1: 'Basal cell carcinoma (bcc)',
    2: 'Benign keratosis-like lesions (bkl)',
    3: 'Dermatofibroma (df)',
    4: 'Melanocytic nevi (nv)',
    5: 'Melanoma (mel)',
    6: 'Vascular lesions (vasc)'
}

def detect_skin_disease():
    # Ask you to upload an image
    uploaded = files.upload()

    for fn in uploaded.keys():
        # Load and resize the image for the AI
        img_path = fn
        img = image.load_img(img_path, target_size=(224, 224))

        # Convert image to numbers (array)
        img_array = image.img_to_array(img) / 255.0
        img_array = np.expand_dims(img_array, axis=0)

        # The AI makes a prediction
        prediction = model.predict(img_array)

        # Find the highest score
        result_index = np.argmax(prediction)
        confidence = np.max(prediction) * 100

        # Display the image and result
        plt.imshow(img)
        plt.title(f"Result: {disease_map[result_index]}\nConfidence: {confidence:.2f}%")
        plt.axis('off')
        plt.show()

# RUN THE DETECTION
detect_skin_disease()